import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { decodeOp, encodeOp, type WireOp } from './codec'
import { RgaDocument } from './document'

/**
 * The test that ties two implementations of one algorithm together.
 *
 * The CRDT decision accepts a deliberate debt: RGA exists in Java (the server) and in TypeScript (the client
 * that edits offline). Two implementations of one specification will diverge sooner or later, and
 * it will manifest as the worst possible bug — "it looks different on my side than on yours".
 *
 * The vectors in `conformance/` are GENERATED by the Java tests and versioned in the repository.
 * This test replays them step by step. CI runs both sides and separately checks that the corpus in
 * the repository is current with respect to the Java implementation — so divergence cannot pass
 * silently in either direction.
 */

interface ExpectedSpan {
  from: number
  to: number
  marks: Record<string, string | null>
}

interface Vector {
  name: string
  description: string
  operations: WireOp[]
  expectedText: string
  /**
   * The expected formatting (CP13). Present in EVERY vector, including those with no marks — as an
   * empty array in that case. A conditionally present field would make it impossible to tell "no
   * formatting" from "an old vector without this field".
   */
  expectedFormatting: ExpectedSpan[]
}

/** The document's formatting in a shape comparable with a vector. */
function describeFormatting(document: RgaDocument): ExpectedSpan[] {
  return document.formatting().map((span) => ({
    from: span.from,
    to: span.to,
    marks: Object.fromEntries(span.marks),
  }))
}

const VECTOR_DIR = join(__dirname, '..', '..', '..', 'conformance')

function loadVectors(): Vector[] {
  const files = readdirSync(VECTOR_DIR).filter((name) => name.endsWith('.json')).sort()
  return files.map((file) => JSON.parse(readFileSync(join(VECTOR_DIR, file), 'utf8')) as Vector)
}

describe('conformance with the Java implementation', () => {
  const vectors = loadVectors()

  it('the vector corpus is non-empty', () => {
    // Without this assertion, an empty or wrongly pointed directory would give a green run and the
    // whole protection against divergence would silently stop working.
    expect(vectors.length).toBeGreaterThan(15)
  })

  for (const vector of vectors) {
    it(`${vector.name} — ${vector.description}`, () => {
      const document = new RgaDocument(999)
      document.applyAll(vector.operations.map(decodeOp))

      expect(document.text).toBe(vector.expectedText)
      expect(document.pendingCount, 'operations were left in the buffer').toBe(0)

      // Text convergence does NOT prove formatting convergence: marks have their own set of
      // operations and their own resolution rule, so the two implementations can produce the same
      // text and a different appearance. Comparing text alone would let such a divergence through
      // entirely.
      expect(describeFormatting(document), 'the formatting diverged from the Java implementation')
        .toEqual(vector.expectedFormatting)
    })
  }

  it('a round trip through the codec does not change an operation', () => {
    for (const vector of vectors) {
      for (const wire of vector.operations) {
        expect(encodeOp(decodeOp(wire))).toEqual(wire)
      }
    }
  })

  it('delivery order does not change the result', () => {
    // The vectors are stored in a specific order, but convergence is supposed to depend on none.
    // Reversing them is a cheap, deterministic check of that property on the TS side — full random
    // permutations are the job of the property test in Java.
    for (const vector of vectors) {
      const reversed = new RgaDocument(999)
      reversed.applyAll([...vector.operations].reverse().map(decodeOp))
      expect(reversed.text, `vector ${vector.name} depends on order`).toBe(vector.expectedText)
      expect(
        describeFormatting(reversed),
        `the formatting of vector ${vector.name} depends on delivery order`,
      ).toEqual(vector.expectedFormatting)
    }
  })
})
