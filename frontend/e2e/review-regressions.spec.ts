import { expect, test, freshDocument, joinAs, API, APP } from './helpers'

test('replacement undo restores text in a single transaction', async ({ browser, request }) => {
  const id = await freshDocument(request, 'Replacement regression')
  const page = await joinAs(browser, 'Undo reviewer', id)
  const editor = page.locator('.cm-content')
  await editor.fill('abc')
  await expect(page.locator('.save-state')).toContainText('Saved')
  await editor.fill('xyz')
  await editor.press('ControlOrMeta+z')
  await expect(editor).toHaveText('abc')
  await page.context().close()
})

test('large paste redo remains synchronized with another client', async ({ browser, request }) => {
  const id = await freshDocument(request, 'Large redo regression')
  const anna = await joinAs(browser, 'Anna', id)
  const marek = await joinAs(browser, 'Marek', id)
  const text = 'x'.repeat(100_000)
  await anna.locator('.cm-content').fill(text)
  await expect(marek.getByTestId('char-count')).toContainText('100000 characters', { timeout: 30_000 })
  await anna.locator('.cm-content').press('ControlOrMeta+z')
  await expect(marek.getByTestId('char-count')).toContainText('0 characters', { timeout: 30_000 })
  await anna.locator('.cm-content').press('ControlOrMeta+Shift+z')
  await expect(marek.getByTestId('char-count')).toContainText('100000 characters', { timeout: 30_000 })
  await expect(anna.locator('.save-state')).toContainText('Saved', { timeout: 30_000 })
  await anna.context().close()
  await marek.context().close()
})

test('comment replies refresh for another client without a text edit', async ({ browser, request }) => {
  const id = await freshDocument(request, 'Reply refresh regression')
  const anna = await joinAs(browser, 'Anna', id)
  const marek = await joinAs(browser, 'Marek', id)
  await anna.locator('.cm-content').fill('Discuss this')
  await expect(marek.locator('.cm-content')).toContainText('Discuss this')
  await anna.locator('.cm-content').press('ControlOrMeta+a')
  await anna.getByRole('button', { name: 'Comments', exact: true }).click()
  await anna.getByLabel('Your comment', { exact: true }).fill('First comment')
  await anna.getByRole('button', { name: 'Comment', exact: true }).click()
  await marek.getByRole('button', { name: 'Comments', exact: true }).click()
  await expect(marek.locator('.comment-thread')).toContainText('First comment', { timeout: 15_000 })
  await anna.getByRole('button', { name: 'Reply', exact: true }).click()
  await anna.locator('.comment-reply').fill('Reply without typing in the document')
  await anna.locator('.comment-reply').press('Enter')
  await expect(marek.locator('.comment-thread')).toContainText('Reply without typing in the document', { timeout: 15_000 })
  await anna.context().close()
  await marek.context().close()
})

test('mobile layout keeps the editor usable and documents accessible', async ({ browser, request }) => {
  const id = await freshDocument(request, 'Mobile regression')
  const page = await joinAs(browser, 'Mobile reviewer', id)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.sidebar')).not.toBeVisible()
  await expect(page.locator('.cm-content')).toBeVisible()
  await page.getByRole('button', { name: 'Documents', exact: true }).click()
  await expect(page.locator('.sidebar')).toBeVisible()
  await page.getByRole('button', { name: 'Close documents', exact: true }).click()
  await expect(page.locator('.sidebar')).not.toBeVisible()
  await page.context().close()
})

test('restoring a deleted document opened directly reopens its editor', async ({ browser, request }) => {
  const login = await request.post(`${API}/login`, { data: { displayName: 'Restore reviewer' } })
  expect(login.ok()).toBeTruthy()
  const session = await login.json() as { token: string }
  const headers = { Authorization: `Bearer ${session.token}` }
  const created = await request.post(`${API}/documents`, { headers, data: { title: 'Direct restore regression' } })
  expect(created.ok()).toBeTruthy()
  const { id } = await created.json() as { id: string }
  expect((await request.delete(`${API}/documents/${id}`, { headers })).status()).toBe(204)
  const context = await browser.newContext()
  await context.addInitScript(value => localStorage.setItem('collabedit.session', JSON.stringify(value)), session)
  const page = await context.newPage()
  await page.goto(`${APP}/?doc=${id}`)
  await expect(page.locator('.unavailable-banner')).toBeVisible()
  await page.getByRole('button', { name: 'Bin', exact: true }).click()
  await page.getByRole('button', { name: 'Restore Direct restore regression', exact: true }).click()
  await expect(page.locator('.unavailable-banner')).toHaveCount(0)
  await expect(page.locator('.cm-content')).toHaveAttribute('contenteditable', 'true')
  await context.close()
})
