-- The column default that made every forgotten INSERT world-editable.
--
-- V3 added `visibility TEXT NOT NULL DEFAULT 'link'`, and the default was right at the time: link
-- visibility was how the product worked, and CP12 had no business taking access away from documents
-- people were already opening. CP21 changed what CREATION means — a new document is private, and
-- sharing is a gesture — but it changed it in `DocumentRestController`, by following the INSERT with
-- an explicit `setVisibility`. The column went on saying `link`.
--
-- So the safety of every new document rested on the caller remembering a second call. `DocumentCatalog.create`
-- did not make it, which is why a database that had been developed against for two days held 132
-- link-visible documents and one private one — and, login being passwordless, every one of those 132
-- was editable by anybody who typed a name into the login box.
--
-- This is exactly the argument V10 made about `document_members.role`, under "WHY THE DEFAULT GOES
-- TOO": a default that GRANTS is a decision nobody takes on purpose. `create` now names the value,
-- so an INSERT that forgets is a NOT NULL violation — loud, at the moment of the mistake — rather
-- than a document quietly readable by the world.
--
-- EXISTING ROWS ARE NOT TOUCHED, and that is deliberate rather than an omission. Rewriting them to
-- private would take away access to documents people are currently sharing by link, which is the
-- thing V3's own reasoning refuses to do, and this migration has no way to tell a deliberate share
-- from an accidental default. What made those rows dangerous was not the value itself but that the
-- document LIST handed their URLs to everybody; that is fixed in `DocumentCatalog.READABLE_BY_CALLER`,
-- where the reasoning is written out. A link-visible document is now what it says on the tin:
-- reachable by anyone who has the address, invisible to everyone who does not.
ALTER TABLE documents ALTER COLUMN visibility DROP DEFAULT;
